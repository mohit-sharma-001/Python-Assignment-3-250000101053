# Question 50: Write a program to create two sets and perform union, intersection, difference and symmetric difference operations.

set_a = {1, 2, 3, 4, 5}
set_b = {4, 5, 6, 7, 8}

print("Set A:", set_a)
print("Set B:", set_b)

print("Union (A | B)               :", set_a | set_b)
print("Intersection (A & B)        :", set_a & set_b)
print("Difference (A - B)          :", set_a - set_b)
print("Symmetric Difference (A ^ B):", set_a ^ set_b)
