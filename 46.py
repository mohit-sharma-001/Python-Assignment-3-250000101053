# Question 46: Write a program to create a tuple and access its elements using positive and negative indexing.

t = (10, 20, 30, 40, 50)

print("Tuple:", t)
print("Positive indexing:")
print("t[0] =", t[0])
print("t[2] =", t[2])

print("Negative indexing:")
print("t[-1] =", t[-1])
print("t[-2] =", t[-2])
