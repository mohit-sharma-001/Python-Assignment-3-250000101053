# Question 48: Write a program to demonstrate tuple concatenation, repetition and slicing.

t1 = (1, 2, 3)
t2 = (4, 5)

# Concatenation
cat = t1 + t2
print("Concatenation (t1 + t2):", cat)

# Repetition
rep = t1 * 3
print("Repetition (t1 * 3):", rep)

# Slicing
t_full = (10, 20, 30, 40, 50, 60)
print("Slicing (t_full[1:4]):", t_full[1:4])
